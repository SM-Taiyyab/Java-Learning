package Learn_java;

public class While_loop
{
    public static void main(String[] args)
    {
        int x = 1;
        while (x <= 4)
        {
            System.out.println("taiyyab" + x);

            int j = 1;
            while (j <= 3)
            {
                System.out.println("Hello");
                j++;
            }
            x++;
        }
    }
}